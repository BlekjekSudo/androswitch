"""Regenerate bounded charset-recognition data from the pinned API 26 ICU table.

Only alias data is derived from ICU. The Rust encoders are original code. This
script never downloads during a build; pass the frozen source explicitly.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

SOURCE_SHA256 = "446d9587e344c9cc55af1c878f439e1c96efae3487b02b7f561ba21527b33227"
ENCODERS = {
    "UTF-8": "Utf8", "UTF-16": "Utf16", "UTF-16BE": "Utf16Be",
    "UTF-16LE": "Utf16Le", "ISO-8859-1": "Latin1", "US-ASCII": "Ascii",
}


def key(name):
    """ASCII ICU alias comparison: punctuation resets numeric-run state."""
    result = []
    after_digit = False
    for index, char in enumerate(name):
        if not char.isascii() or not char.isalnum():
            after_digit = False
        elif char == "0":
            if not after_digit and index + 1 < len(name) and name[index + 1] in "0123456789":
                continue
            result.append(char)
        elif char in "123456789":
            after_digit = True
            result.append(char)
        else:
            after_digit = False
            result.append(char.lower())
    return "".join(result)


def generate(source):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise SystemExit("ICU alias source checksum differs from the frozen API 26 input")
    groups = {}
    current = None
    brace_depth = 0
    for line in raw.decode("utf-8-sig").splitlines():
        line = line.split("#", 1)[0]
        cleaned = []
        for char in line:
            if char == "{":
                brace_depth += 1
            elif char == "}":
                brace_depth -= 1
                if brace_depth < 0:
                    raise ValueError("Unbalanced ICU tags")
            elif not brace_depth:
                cleaned.append(char)
        words = "".join(cleaned).split()
        if not words:
            continue
        if line and not line[0].isspace():
            current = words[0]
            groups[current] = []
        if current is None:
            raise ValueError("Alias without converter")
        groups[current].extend(words)
    if brace_depth:
        raise ValueError("Unterminated ICU tags")
    known = sorted({key(alias) for names in groups.values() for alias in names})
    supported = {}
    for canonical, encoder in ENCODERS.items():
        for alias in groups[canonical]:
            # Versioned/BOM-producing converters are separate groups, never
            # silently substituted with the six implemented encoders.
            lowered = alias.lower()
            if lowered in supported and supported[lowered] != encoder:
                raise ValueError("Ambiguous implemented alias")
            supported[lowered] = encoder
    # Documented ICU spelling equivalence; these common Java spellings are
    # explicit here rather than treating arbitrary normalized names as encoders.
    for alias, encoder in {
        "utf8": "Utf8", "utf_8": "Utf8", "utf16": "Utf16",
        "utf_16": "Utf16", "utf16be": "Utf16Be", "utf16le": "Utf16Le",
        "iso8859-1": "Latin1", "iso8859_1": "Latin1", "iso_8859_1": "Latin1",
    }.items():
        supported[alias] = encoder
    header = """// Generated by scripts/generate-android26-charsets.py; do not edit.
// Alias data: Android android-8.0.0_r1 ICU convrtrs.txt, SHA256
// 446d9587e344c9cc55af1c878f439e1c96efae3487b02b7f561ba21527b33227.
// Copyright (C) 2016 and later: Unicode, Inc. and others.
// Copyright (C) 1995-2014 IBM Corporation and others. All Rights Reserved.
// Retained license/provenance: third_party/android-charset/{LICENSE,SOURCE.md}.
// KNOWN_KEYS recognizes missing converters; it does not implement them.
use super::string_encoding::Encoding;
pub(super) static IMPLEMENTED_ALIASES: &[(&str, Encoding)] = &[\n"""
    for name, encoder in sorted(supported.items()):
        header += f'    ({json.dumps(name)}, Encoding::{encoder}),\n'
    header += "];\npub(super) static KNOWN_KEYS: &[&str] = &[\n"
    for name in known:
        header += f"    {json.dumps(name)},\n"
    header += "];\n"
    return header, {"converter_groups": len(groups), "known_normalized_keys": len(known),
                    "implemented_aliases": len(supported), "input_sha256": SOURCE_SHA256}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] /
                        "crates/rd-vm/src/portable/charset_catalog.rs")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated, info = generate(args.source)
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit("Generated charset catalog differs")
    else:
        args.output.write_text(generated, encoding="utf-8", newline="\n")
    print(json.dumps(info, sort_keys=True))


if __name__ == "__main__":
    main()
