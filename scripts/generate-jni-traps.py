"""Generate named failure thunks from the pinned AOSP JNI ABI header."""
import pathlib
import re
root = pathlib.Path(__file__).resolve().parent.parent
header = (root / "third_party/android/jni.h").read_text()
interface = header.split("struct JNINativeInterface {", 1)[1].split("\n};", 1)[0]
names = re.findall(r"\(\*(\w+)\)", interface)
assert names[0] == "GetVersion" and names[-1] == "GetObjectRefType"
lines = ["/* Generated by scripts/generate-jni-traps.py; do not edit. */"]
for slot, name in enumerate(names, 4):
    lines.append(f'static uint64_t missing_{name}(void) {{ as_jni_missing({slot}, "{name}"); return 0; }}')
lines.append("static const void *missing_functions[] = {NULL,NULL,NULL,NULL,")
lines.extend(f"    (const void*)missing_{name}," for name in names)
lines.append("};")
(root / "platform/switch-smoke/jni_traps.inc").write_text("\n".join(lines) + "\n")
print(f"Generated {len(names)} named JNI failure entries")
